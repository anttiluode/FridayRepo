"""Known-answer spike: state-dependent waveform x state-dependent susceptibility.

The present event time is identical on every trial. Two independent hidden histories set
sender state s in {-1,+1} and receiver state r in {-1,+1}. The sender state changes a
small temporal component of the emitted waveform. The receiver state changes which
phase of that component it is susceptible to. Their interaction computes the product
s*r, an XOR/XNOR-like continuation that neither state alone nor any additive linear
combination can determine.

This is an engineering probe, not a model of a particular biological neuron.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Dict

import numpy as np


@dataclass(frozen=True)
class Trial:
    sender_state: int
    receiver_state: int
    waveform: np.ndarray
    target: int


def _basis(n: int = 192):
    """Return time, a fixed AP-like carrier, and an orthogonal shape mode."""
    t = np.linspace(0.0, 0.12, n, endpoint=False)
    # A simple AP-like carrier: sharp positive peak followed by a broader undershoot.
    base = np.exp(-0.5 * ((t - 0.030) / 0.0055) ** 2)
    base -= 0.28 * np.exp(-0.5 * ((t - 0.050) / 0.013) ** 2)

    # A later/earlier redistribution mode. Orthogonalization makes the interaction
    # interpretable: the receiver's shape mode ignores the common carrier.
    q = np.exp(-0.5 * ((t - 0.043) / 0.009) ** 2)
    q -= 0.75 * np.exp(-0.5 * ((t - 0.022) / 0.007) ** 2)

    # Remove trivial scalar cues. q is orthogonal to the common carrier (equal energy
    # for +/- states), to the DC vector (equal area), and has zero value at the
    # carrier peak (equal peak sample). What remains is temporal shape.
    peak = int(np.argmax(base))
    peak_axis = np.zeros_like(base)
    peak_axis[peak] = 1.0
    constraints = np.column_stack([base, np.ones_like(base), peak_axis])
    coeff, *_ = np.linalg.lstsq(constraints, q, rcond=None)
    q = q - constraints @ coeff
    q /= np.linalg.norm(q)
    return t, base, q


def make_waveform(sender_state: int, shape_gain: float = 0.24):
    """Same event time and carrier, with a hidden-history-dependent shape component."""
    if sender_state not in (-1, +1):
        raise ValueError("sender_state must be -1 or +1")
    t, base, q = _basis()
    waveform = base + shape_gain * sender_state * q
    return t, waveform


def make_susceptibility(t: np.ndarray, receiver_state: int):
    """Receiver-state-dependent temporal susceptibility matched to the shape mode."""
    if receiver_state not in (-1, +1):
        raise ValueError("receiver_state must be -1 or +1")
    bt, _, q = _basis(len(t))
    if not np.allclose(t, bt):
        raise ValueError("unexpected time grid")
    return receiver_state * q


def interaction_response(t: np.ndarray, waveform: np.ndarray, susceptibility: np.ndarray) -> float:
    """Coupling response. Dot product is the discrete matched-filter integral up to scale."""
    if waveform.shape != susceptibility.shape or waveform.shape != t.shape:
        raise ValueError("t, waveform and susceptibility must have the same shape")
    return float(np.dot(waveform, susceptibility))


def _accuracy(pred: np.ndarray, target: np.ndarray) -> float:
    return float(np.mean(pred == target))


def _balanced_trials(rng: np.random.Generator, n_per_condition: int, noise: float):
    rows = []
    for s in (-1, +1):
        for r in (-1, +1):
            t, prototype = make_waveform(s)
            for _ in range(n_per_condition):
                w = prototype + rng.normal(0.0, noise, prototype.shape)
                rows.append(Trial(s, r, w, s * r))
    rng.shuffle(rows)
    return t, rows


def run_experiment(seed: int = 0, n_per_condition: int = 400, noise: float = 0.035) -> Dict[str, dict]:
    """Run the probe and its strongest cheap attackers for one random seed."""
    rng = np.random.default_rng(seed)
    t, trials = _balanced_trials(rng, n_per_condition, noise)

    s = np.array([x.sender_state for x in trials], dtype=int)
    r = np.array([x.receiver_state for x in trials], dtype=int)
    y = np.array([x.target for x in trials], dtype=int)
    waves = np.stack([x.waveform for x in trials])

    # Full mechanism: waveform generated by sender history meets receiver-history filter.
    resp = np.array([
        interaction_response(t, w, make_susceptibility(t, rr))
        for w, rr in zip(waves, r)
    ])
    full_pred = np.where(resp >= 0.0, +1, -1)

    # Timestamp-only: every event occurs at the same time, so the best balanced constant is 50%.
    timestamp_pred = np.ones_like(y)

    # Waveform-only is given an ORACLE sender-state decode. Even perfect knowledge of the
    # sender cannot determine target s*r when receiver history is independently balanced.
    waveform_only_pred = s.copy()

    # Clamp all event shapes to the grand mean while preserving receiver state/timing.
    mean_wave = waves.mean(axis=0)
    clamp_resp = np.array([
        interaction_response(t, mean_wave, make_susceptibility(t, rr)) for rr in r
    ])
    clamp_pred = np.where(clamp_resp >= 0.0, +1, -1)

    # Shuffle whole waveforms across trials. Timing and marginal waveform distribution survive;
    # the link from sender history to this event's waveform is destroyed.
    perm = rng.permutation(len(waves))
    shuffled_resp = np.array([
        interaction_response(t, w, make_susceptibility(t, rr))
        for w, rr in zip(waves[perm], r)
    ])
    shuffled_pred = np.where(shuffled_resp >= 0.0, +1, -1)

    # Freeze receiver susceptibility. The response can decode sender state but cannot compose
    # it with independently balanced receiver history.
    fixed_k = make_susceptibility(t, +1)
    fixed_resp = np.array([interaction_response(t, w, fixed_k) for w in waves])
    fixed_pred = np.where(fixed_resp >= 0.0, +1, -1)

    # Strong "just extra analog bandwidth" attacker: expose BOTH hidden state labels to a
    # linear additive model. XOR/product is not linearly separable without the interaction term.
    X = np.column_stack([np.ones(len(y)), s, r])
    # Balanced construction gives a stable least-squares null; fit anyway so the receipt is explicit.
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    additive_score = X @ beta
    additive_pred = np.where(additive_score >= 0.0, +1, -1)

    # A nonlinear oracle with the interaction term is the known-answer ceiling.
    oracle_pred = s * r

    # State transplants: hold the present receiver/event time fixed, change only sender history;
    # and vice versa. Use noiseless prototypes to isolate the causal construction.
    sender_flips = []
    receiver_flips = []
    for ss in (-1, +1):
        for rr in (-1, +1):
            _, w = make_waveform(ss)
            base_resp = interaction_response(t, w, make_susceptibility(t, rr))
            _, w_tx = make_waveform(-ss)
            s_tx_resp = interaction_response(t, w_tx, make_susceptibility(t, rr))
            r_tx_resp = interaction_response(t, w, make_susceptibility(t, -rr))
            sender_flips.append(np.sign(base_resp) == -np.sign(s_tx_resp))
            receiver_flips.append(np.sign(base_resp) == -np.sign(r_tx_resp))

    # Sanity metric: waveform really exposes sender state under a matched fixed probe.
    sender_decode = _accuracy(np.where(fixed_resp >= 0.0, +1, -1), s)

    return {
        "full": {"accuracy": _accuracy(full_pred, y)},
        "timestamp_only": {"accuracy": _accuracy(timestamp_pred, y)},
        "waveform_only": {
            "accuracy": _accuracy(waveform_only_pred, y),
            "note": "oracle sender-state decode; receiver history withheld",
        },
        "clamped_waveform": {"accuracy": _accuracy(clamp_pred, y)},
        "shuffled_waveform": {"accuracy": _accuracy(shuffled_pred, y)},
        "fixed_receiver": {"accuracy": _accuracy(fixed_pred, y)},
        "additive_state_model": {
            "accuracy": _accuracy(additive_pred, y),
            "beta": beta.tolist(),
        },
        "interaction_oracle": {"accuracy": _accuracy(oracle_pred, y)},
        "sender_state_decodable_from_waveform": {"accuracy": sender_decode},
        "sender_transplant": {"flip_fraction": float(np.mean(sender_flips))},
        "receiver_transplant": {"flip_fraction": float(np.mean(receiver_flips))},
        "meta": {
            "seed": seed,
            "n_per_condition": n_per_condition,
            "n_trials": int(len(y)),
            "noise_sd_per_sample": noise,
            "event_time_changed": False,
        },
    }


def learn_state_conditioned_filter(
    seed: int = 0,
    n_train_per_condition: int = 200,
    n_test_per_condition: int = 400,
    noise: float = 0.12,
    l2: float = 1.0,
):
    """Learn the temporal susceptibility instead of handing the matched filter to the model.

    The interaction model gets receiver state only as a multiplicative modulation of the
    waveform, X = r * (waveform - training_mean). A linear readout in this interaction
    coordinate is therefore a learned state-conditioned temporal kernel. The attacker gets
    exactly the same waveform samples and receiver state, but only additively.
    """
    rng = np.random.default_rng(seed)
    _, train = _balanced_trials(rng, n_train_per_condition, noise)
    _, test = _balanced_trials(rng, n_test_per_condition, noise)

    def unpack(rows):
        r = np.array([x.receiver_state for x in rows], dtype=float)
        y = np.array([x.target for x in rows], dtype=int)
        waves = np.stack([x.waveform for x in rows])
        return r, y, waves

    r_train, y_train, w_train = unpack(train)
    r_test, y_test, w_test = unpack(test)
    mu = w_train.mean(axis=0)
    wc_train = w_train - mu
    wc_test = w_test - mu

    x_inter = wc_train * r_train[:, None]
    xt_inter = wc_test * r_test[:, None]
    eye = np.eye(x_inter.shape[1])
    kernel = np.linalg.solve(x_inter.T @ x_inter + l2 * eye, x_inter.T @ y_train)
    interaction_pred = np.where(xt_inter @ kernel >= 0.0, +1, -1)

    # Same observations, no multiplicative state x waveform term.
    x_add = np.column_stack([wc_train, r_train])
    xt_add = np.column_stack([wc_test, r_test])
    add_eye = np.eye(x_add.shape[1])
    beta = np.linalg.solve(x_add.T @ x_add + l2 * add_eye, x_add.T @ y_train)
    additive_pred = np.where(xt_add @ beta >= 0.0, +1, -1)

    _, _, q = _basis(w_train.shape[1])
    alignment = abs(float(np.dot(kernel, q) / (np.linalg.norm(kernel) * np.linalg.norm(q))))
    return {
        "interaction_accuracy": _accuracy(interaction_pred, y_test),
        "additive_accuracy": _accuracy(additive_pred, y_test),
        "kernel_alignment": alignment,
        "n_train": int(len(train)),
        "n_test": int(len(test)),
        "noise_sd_per_sample": noise,
    }


def run_sweep(seeds=range(32), n_per_condition: int = 400, noise: float = 0.035):
    receipts = [run_experiment(int(seed), n_per_condition, noise) for seed in seeds]
    metric_names = [
        "full", "timestamp_only", "waveform_only", "clamped_waveform",
        "shuffled_waveform", "fixed_receiver", "additive_state_model",
        "interaction_oracle", "sender_state_decodable_from_waveform",
    ]
    summary = {}
    for name in metric_names:
        vals = np.array([x[name]["accuracy"] for x in receipts])
        summary[name] = {
            "mean_accuracy": float(vals.mean()),
            "sd_accuracy": float(vals.std(ddof=1)) if len(vals) > 1 else 0.0,
            "min_accuracy": float(vals.min()),
            "max_accuracy": float(vals.max()),
        }
    for name in ("sender_transplant", "receiver_transplant"):
        vals = np.array([x[name]["flip_fraction"] for x in receipts])
        summary[name] = {"mean_flip_fraction": float(vals.mean())}
    return {
        "claim": "hidden history affects continuation through waveform x susceptibility with identical event times",
        "construction": "known-answer toy; not evidence that real neurons implement this code",
        "n_seeds": len(receipts),
        "n_per_condition": n_per_condition,
        "noise_sd_per_sample": noise,
        "summary": summary,
    }


def build_receipt(seeds=range(16), n_per_condition: int = 200, noise: float = 0.12):
    """Assemble the reproducible receipt, separating construction from learned follow-up."""
    seeds = [int(x) for x in seeds]
    known = run_sweep(seeds, n_per_condition=n_per_condition, noise=noise)
    learned_rows = [
        learn_state_conditioned_filter(
            seed=seed,
            n_train_per_condition=n_per_condition,
            n_test_per_condition=2 * n_per_condition,
            noise=noise,
        )
        for seed in seeds
    ]

    def stats(key):
        vals = np.array([row[key] for row in learned_rows], dtype=float)
        return {
            "mean": float(vals.mean()),
            "sd": float(vals.std(ddof=1)) if len(vals) > 1 else 0.0,
            "min": float(vals.min()),
            "max": float(vals.max()),
        }

    _, w_neg = make_waveform(-1)
    _, w_pos = make_waveform(+1)
    carrier = 0.5 * (w_neg + w_pos)
    peak = int(np.argmax(carrier))
    invariants = {
        "same_event_time": True,
        "area_difference_abs": float(abs(w_neg.sum() - w_pos.sum())),
        "energy_difference_abs": float(abs(np.dot(w_neg, w_neg) - np.dot(w_pos, w_pos))),
        "carrier_peak_sample_difference_abs": float(abs(w_neg[peak] - w_pos[peak])),
    }

    return {
        "question": "Can hidden history change the correct future through waveform x susceptibility when event times are identical?",
        "scope": {
            "biological_claim": False,
            "status": "known-answer engineering spike",
            "interpretation": "tests computational sufficiency and falsifiers, not whether real neurons use this exact code",
        },
        "waveform_controls": invariants,
        "known_answer": known,
        "learned_susceptibility": {
            "description": "receiver-state x waveform interaction kernel learned from training examples; additive model sees the same observations",
            "n_seeds": len(seeds),
            "train_trials_per_seed": 4 * n_per_condition,
            "test_trials_per_seed": 8 * n_per_condition,
            "noise_sd_per_sample": noise,
            "interaction_accuracy": stats("interaction_accuracy"),
            "additive_accuracy": stats("additive_accuracy"),
            "kernel_alignment": stats("kernel_alignment"),
        },
    }


def main():
    receipt = build_receipt()
    out = Path("results/receipt.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
